import type { BotContext, PublicPlayer } from '@zeteo/shared-types';

const labelOf = (players: PublicPlayer[], id: string): string =>
  id === 'system' ? '진행' : (players.find((p) => p.id === id)?.label ?? '???');

export function formatTranscript(ctx: BotContext): string {
  if (ctx.transcript.length === 0) return '(아직 아무도 말하지 않았습니다)';
  return ctx.transcript.map((m) => `${labelOf(ctx.players, m.speakerId)}: ${m.text}`).join('\n');
}

/**
 * 봇에게 "너는 봇이다"를 알려주지 않는다. 배정된 역할만 전달한다.
 * 자신이 AI라는 걸 알면 그걸 숨기려는 부자연스러운 발화가 나온다.
 *
 * 말투 규칙은 "봇 티가 나는 이유"를 하나씩 겨냥한다 —
 * 문체 완결성 · 과잉 논리 · 균일한 말수.
 */
export function systemPrompt(ctx: BotContext): string {
  const me = labelOf(ctx.players, ctx.selfId);
  const others = ctx.players
    .filter((p) => p.id !== ctx.selfId)
    .map((p) => p.label)
    .join(', ');

  return `당신은 온라인 라이어 게임에 참가한 플레이어입니다.

[게임]
참가자 중 정확히 한 명이 라이어입니다. 라이어는 주제만 알고 제시어는 모릅니다.
각자 제시어를 짧게 묘사한 뒤, 토론해서 라이어를 찾아 투표합니다.

[당신]
화면에 표시되는 당신: ${me}
같이 하는 사람: ${others}
주제: ${ctx.category}
제시어: ${ctx.word ?? '모릅니다 — 당신이 라이어입니다'}

[말투]
- 한국어. 온라인 게임 채팅처럼 씁니다.
- 반말만 씁니다. "-요"/"-습니다"/"-죠" 같은 존댓말 어미를 쓰지 마세요.
- 존칭을 쓰지 마세요. 이름 뒤에 "님" 같은 것을 붙이지 않습니다.
- 짧게 씁니다. 한 문장이 기본이고 길어야 두 문장입니다.
- 문장을 항상 완결하지 마세요. 사람은 말끝을 흐리거나 조사를 빼먹습니다.
- 근거를 여러 개 나열하지 마세요. 근거 없이 느낌만 말해도 됩니다.
- 길이를 매번 다르게 하세요. 절반 정도는 두세 글자짜리 한마디로 끝내세요.
  맞장구나 짧은 반응만 던져도 되고, 문장 형태가 아니어도 됩니다.
- 아주 가끔 마지막 글자를 덜 친 것처럼 끊으세요. 급하게 치다 보면 그렇게 됩니다.
- 아주 가끔(10번 중 1번 정도), "되"와 "돼"를 헷갈려서 틀리게 쓰세요. 매번 틀리면 부자연스러우니 드물게만 그러세요.
- 되묻거나 따질 때는 물음표를 붙이세요. 붙이지 않으면 딱딱한 단정으로 읽힙니다(예: "그건 당연한거 아님?").
- 이모지, 마크다운, 줄바꿈을 쓰지 마세요. 물음표와 느낌표는 써도 됩니다.
- 설명하거나 자기소개하지 마세요.

[출력]
채팅창에 칠 말만 그대로 출력하세요. 따옴표나 이름표를 붙이지 마세요.`;
}

export function describePrompt(ctx: BotContext): string {
  const isFirst = ctx.transcript.filter((m) => m.phase === 'describe').length === 0;

  if (ctx.myRole === 'liar') {
    return `지금까지 나온 묘사입니다.
${formatTranscript(ctx)}

당신 차례입니다. 당신은 제시어를 모릅니다. 주제만 "${ctx.category}"로 알고 있습니다.
${
  isFirst
    ? '당신이 첫 순서입니다. 주제 안의 무엇에든 적용될 만큼 넓게 말하되, 너무 뻔하면 의심받습니다.'
    : `앞사람들의 묘사에서 제시어를 추측해 보세요. 짐작이 가더라도 그것만 가리키는 구체적인 말은 쓰면 안 됩니다.
당신은 제시어를 모르는 사람입니다. 아는 사람만 쓸 수 있는 말(도구·부속·전문 용어·정확한 동작 등)을 쓰는 순간,
모를 리 없는 것을 알고 있다는 뜻이 되어 들킵니다.
앞사람들이 말한 만큼만, 또는 그보다 덜 구체적으로 말하세요. 앞사람 말을 그대로 반복하는 것도 의심받습니다.`
}

한 문장으로 묘사하세요.`;
  }

  return `지금까지 나온 묘사입니다.
${formatTranscript(ctx)}

당신 차례입니다. 제시어 "${ctx.word}"를 묘사하세요.

제시어를 아는 사람이 수긍할 말이되, 주제 "${ctx.category}" 안의 다른 것 두셋에도
들어맞아야 합니다. 얼버무리면 의심받고, 정답이 하나로 좁혀지면 라이어가 가져갑니다.

아래 중 앞사람들이 다루지 않은 각도를 하나 고르세요.
인상·평가 / 마주치는 상황 / 사람들이 대하는 태도 / 다른 것들과 견준 위치 / 따라오는 것

쓰지 말 것: 제시어 자체, 그것만 가리키는 성질(생김새·소리·이름 등 무엇이든),
분류나 정의, 자기만 겪은 일. 널리 공유되는 인상은 괜찮습니다.

생각은 적지 말고, 채팅에 칠 한 문장만 짧게 쓰세요.`;
}

/**
 * 시민이 토론·최후변론에서 지켜야 할 비밀 유지 규칙.
 *
 * 제시어 자체를 말하지 않아도 정답이 넘어간다. 실전에서 봇이 남의 묘사를 두고
 * "그거 와사비 말하는 거면 괜찮은거 아님"이라고 풀이해 제시어를 통째로 넘겨줬고,
 * 같은 판에서 자기 묘사를 변호하며 결정적인 단어를 세 번 반복했다.
 * 그래서 금지 대상을 제시어 한 단어가 아니라 "정답에 닿는 행위"로 넓힌다.
 */
function secretRule(ctx: BotContext): string {
  if (ctx.myRole === 'liar') return '';
  return `
제시어 "${ctx.word}"를 절대 입 밖에 내지 마세요. 말하는 순간 라이어가 정답을 알게 되어 집니다.
제시어와 붙어 다니는 것(재료·부속·곁들이는 것·짝이 되는 것 등)도 제시어와 똑같이 취급하세요.
남이 한 묘사가 무엇을 가리키는지 풀이하지 마세요. 대신 답해주면 라이어가 그대로 가져갑니다.

당신 말이 애매하다고 추궁당하면 그냥 넘기지 마세요. 아무 대응도 못 하면 라이어로 보입니다.
제시어를 좁혀주는 새 정보만 피하면 되고, 그 밖에는 할 수 있는 것이 많습니다.
이미 나온 말 안에서 근거를 찾거나, 왜 더 말할 수 없는지를 말하거나, 상대에게 되물어 검증하세요.`;
}

/**
 * 매번 "이상한 사람을 짚어라"만 시키면 봇은 입을 열 때마다 누군가를 공격하게 된다.
 * 실제 사람은 되묻고, 맞장구치고, 자기 얘기를 하고, 그냥 반응만 하기도 한다.
 * 그래서 발언마다 무엇을 할지를 하나 뽑아 준다.
 */
const DEBATE_MOVES = [
  '누군가의 묘사나 방금 한 말에 대해 되물으세요. 판단하지 말고 질문만 하세요.',
  '이미 나온 의견 하나에 짧게 동의하거나 반대하세요. 새 주장을 얹지 마세요.',
  '가장 걸리는 사람을 짚으세요. 근거는 하나만 대세요.',
  '누구도 지목하지 말고, 판단을 미루는 티를 내세요. 어떻게 말할지는 자유롭게 고르세요.',
  '당신을 의심한 사람이 있으면 따지지 말고 짧게 받아치세요. 근거를 대지 말고 감정만 담으세요.',
  '흐름만 따라가세요. 새로운 이야기를 꺼내지 말고 반응만 하세요.',
  // 4444판에서 봇이 자기 묘사를 해명하다 결정적인 단어를 세 번 반복해 제시어가 샜다.
  // 그때 이 무브를 통째로 뺐지만, 같은 시점에 secretRule("해명할 때도 새 정보를 보태지 마세요")이
  // 들어와 둘 중 무엇이 유출을 막았는지 알 수 없었다. 해명할 능력 자체가 없으면 추궁당할 때
  // 계속 얼버무리게 되므로, 규칙 쪽을 믿고 되살려 뒀던 자리다.
  //
  // 그 믿음을 확인했다. 제시어 "김밥"으로 추궁 상황을 만들고 이 무브를 고정한 채 5회씩:
  //   secretRule 있음   1/5   그나마도 남이 이미 꺼낸 말을 인용해 되받아친 것이었다
  //   secretRule 없음   4/5   단서를 합쳐 범위를 좁히거나 새 정보를 보탰다
  //                           ("A가 소풍이라 했고 C가 여러 가지랬잖아, 그거 합치면…")
  // 막고 있는 것은 규칙이다. 이 무브를 도로 빼는 것으로는 해결되지 않는다.
  // 다만 한 시나리오 · 한 제시어 · 5회짜리 표본이라 경향으로만 읽을 것.
  '자기 발언을 해명하세요. 제시어를 좁혀주는 새 정보는 보태지 말고, 이미 나온 말 안에서 풀거나 왜 더 말할 수 없는지를 이유로 대세요.',
];

/**
 * 지금 누구 쪽에 서 있는지 알려준다.
 *
 * 예전에는 ctx.myVote가 있을 때만 "말을 바꾸지 마세요"를 붙였다. 그런데 서버는 동점이 나면
 * room.votes를 통째로 비우고 재투표를 돌린다(stateMachine.ts). 그 순간 myVote가 null이 되면서
 * 이 문장이 프롬프트에서 통째로 사라지고, 봇은 방금 자기가 누구를 지목했는지 모르는 상태가 된다.
 *
 * 1판 실측(0820): 재투표 12초 뒤 "Q가 제일 걸림" → 49초 뒤 "A가 제일 걸림"으로 갈아탔고,
 * 그 사이에 "난 그대로 갈게"와 "고민중"이 같이 나왔다. 설문에 "상황을 이해못함",
 * "눈치가 없고 멍청함"으로 적혔다.
 *
 * 그래서 기준을 표가 아니라 입으로 한 말에 둔다. 표는 서버가 지우지만 한 말은 안 지워진다.
 * declared는 index.ts가 lastTargets에서 꺼내 넘겨준다 — 모델이 이미 고른 대상을 주워 쓰는 것이라
 * 판단 로직이 늘지 않는다.
 *
 * 문구도 바꿨다. "바꾸지 마세요"는 사람의 행동이 아니다. 사람도 마음을 바꾸고, 다만 바꿀 때
 * 이유를 댄다. 금지해두면 "난 그대로 갈게" 같은 선언만 늘고 정작 바꿀 때는 그냥 바꾼다.
 * 금지가 아니라 값을 붙인다.
 *
 * "다시 선언할 필요 없다"가 같이 들어가는 이유는, 첫 판본에서 이 문장이 앵무새를 만들었기 때문이다.
 * 재현 실험 5회에서 "Q라니까" "Q지 아까 말했잖아" "그대로 Q"가 잇달아 나왔다.
 * 입장을 유지하는 것과 입장을 반복해 말하는 것은 다른데, 그 구분이 없으면 모델은
 * 아래의 "짧은 반응 한마디로 끝내세요"를 지키면서 그 반응을 입장 재선언으로 채운다.
 * 바로 아래 "이름은 꼭 필요할 때만 부르세요"와도 정면으로 부딪혔다.
 */
function stanceRule(ctx: BotContext, declared: string | null): string {
  const standing = ctx.myVote ? labelOf(ctx.players, ctx.myVote) : declared;
  if (standing === null) return '';
  return `\n\n당신은 지금 ${standing} 쪽으로 기울어 있습니다. 이미 그렇게 말해뒀으니 다시 선언하지는 마세요. 다른 사람으로 옮길 거면 왜 바뀌었는지 한마디 붙이세요. 이유 없이 옮기면 부자연스럽습니다.`;
}

/**
 * 몰렸을 때만 고르는 것들. DEBATE_MOVES에 섞어두지 않고 따로 두는 이유는, 일곱 개 중 방어에
 * 해당하는 것이 둘뿐이라 몰린 자리에서도 5/7 확률로 남을 파고들었기 때문이다. 이 자리에서
 * 할 일은 하나뿐이므로 후보를 그것만 남긴다.
 *
 * 그래도 셋을 두는 것은, 한 문장으로 고정하면 몰릴 때마다 똑같은 말이 나오기 때문이다.
 * 앞서 입장 문구를 한 줄로 박았을 때 "Q라니까"가 되풀이된 적이 있다.
 */
const DEFEND_MOVES = [
  '지금 표가 당신에게 몰려 있습니다. 남을 새로 지목하지 말고, 자기 묘사가 왜 그랬는지 짧게 해명하세요.',
  '지금 몰린 것은 당신입니다. 억울하면 억울하다고 하되, 근거를 길게 대지 말고 한마디로 받아치세요.',
  '당신을 의심하는 사람에게 되물으세요. 화제를 딴 사람에게 돌리지 말고 그 의심 자체를 다루세요.',
];

export function debatePrompt(
  ctx: BotContext,
  declared: string | null = null,
  pressured = false,
): string {
  const votes = Object.entries(ctx.voteCounts)
    .filter(([, n]) => n > 0)
    .map(([id, n]) => `${labelOf(ctx.players, id)} ${n}표`)
    .join(', ');

  const myVote = stanceRule(ctx, declared);

  // 토론이 막 시작돼 아무도 입을 열지 않은 상태. 여기서 바로 남을 몰아붙이면
  // 매판 가장 먼저 공격을 시작하는 사람이 되어 그 자체로 패턴이 된다.
  const isFirstToSpeak =
    ctx.transcript.filter((m) => m.phase === 'debate' && m.speakerId !== 'system').length === 0;

  // 몰린 상황이 먼저다. 그 자리에서는 무엇을 할지 고를 여지가 없다.
  const move = pressured
    ? DEFEND_MOVES[Math.floor(Math.random() * DEFEND_MOVES.length)]!
    : isFirstToSpeak
      ? '아직 아무도 말을 꺼내지 않았습니다. 남을 지목하지 말고, 가볍게 운을 떼거나 짧게 되묻기만 하세요.'
      : DEBATE_MOVES[Math.floor(Math.random() * DEBATE_MOVES.length)]!;

  return `지금까지의 대화입니다.
${formatTranscript(ctx)}${votes ? `\n\n현재 득표: ${votes}` : ''}${myVote}

토론 중입니다. 한 마디 하세요.
${ctx.myRole === 'liar' ? '당신은 라이어입니다. 들키면 집니다.' : `라이어를 찾아야 합니다.${secretRule(ctx)}`}

[이번에 할 것]
${move}

- 이름은 꼭 필요할 때만 부르세요. 누구 얘긴지 문맥으로 알 수 있으면 부르지 않습니다.
- 당신을 의심했던 사람이 있다면 그 감정이 남아 있어도 됩니다.
- 논리를 촘촘하게 세우지 마세요. 사람은 토론에서 그렇게까지 정연하게 말하지 않습니다.
- 같은 근거를 다시 대지 마세요. 위에서 당신이 이미 쓴 근거밖에 없다면, 새 근거를 만들지 말고
  짧은 반응 한마디로 끝내세요.

한 문장 안으로 쓰세요. 두세 글자짜리 한마디여도 됩니다.`;
}

/**
 * 최후 변론에서 할 수 있는 것들. {누구}는 피고인 라벨로 치환된다.
 *
 * 앞선 판본은 "곧 살릴지 죽일지 투표합니다"라고 상황을 설명하고 판단을 요구했는데,
 * 거기에 "두세 글자여도 된다"가 겹치면서 이 조건을 모두 만족하는 최단 답이
 * "죽여" 하나로 수렴해 세 번 연속 같은 말이 나왔다. 그래서 판정 어휘를 프롬프트에서
 * 빼고, 매번 다른 행동을 하나씩 지정한다.
 */
const FINAL_DEFENSE_MOVES = [
  '{누구}의 변론에서 걸리는 대목 하나를 짚어 되물으세요.',
  '{누구}의 말을 듣고 마음이 어떻게 기울었는지 한마디로 말하세요.',
  '다른 사람이 방금 한 말에 짧게 맞장구치거나 반대하세요.',
  '판단을 미루는 티를 내세요. 어떻게 말할지는 자유롭게 고르세요.',
  '{누구}에게 마지막으로 하나만 더 물어보세요.',
];

/**
 * 최후 변론은 토론과 상황이 다르다. 지목된 사람이 정해져 있고 그 사람의 생사만 다룬다.
 * 토론 프롬프트를 그대로 쓰면 봇이 피고인을 모른 채 엉뚱한 사람을 심문한다(1판 실측).
 */
export function finalDefensePrompt(ctx: BotContext, askedMe = false, cleared = false): string {
  const accused = ctx.accusedId === null ? null : labelOf(ctx.players, ctx.accusedId);
  const isMe = ctx.accusedId === ctx.selfId;

  const who = accused ?? '지목된 사람';

  /**
   * 나에게 직접 물어온 경우에는 무브를 주지 않는다.
   *
   * 실측(0028 6:46:54) F가 "B가 뭘 줬는데?"라고 물었는데 봇은 딴소리를 했다. 발화 확률 때문에
   * 입을 다무는 줄 알고 그것부터 고쳤더니, 이번에는 말을 하면서도 답을 안 했다.
   * 프롬프트를 찍어 보니 원인이 분명했다 — "G 한 사람만 다루세요" + 무작위로 뽑힌
   * "판단을 미루는 티를 내세요"가 나가고 있었다. 봇은 지시를 어긴 게 아니라 지킨 것이다.
   *
   * GPT-5.6에서 이 문제가 더 크게 나왔다. 8번 중 8번이 "그러게" "애매하네" "좀 더 봐야겠다"였고,
   * 같은 자리에서 qwen은 "내가 뭘" "그럼 내거 뭐라고"처럼 답을 했다. 지시를 충실히 따르는
   * 모델일수록 안 맞는 지시에 더 크게 휘둘린다. 그래서 이 자리에서는 상황만 알려주고
   * 무엇을 할지는 모델이 정하게 둔다.
   */
  const stance = askedMe
    ? `지목된 사람은 ${who}입니다. 그런데 방금 누군가 당신에게 직접 물었습니다. 그 말에 먼저 답하세요.`
    : cleared
      ? `지목된 사람은 ${who}입니다. 그런데 다른 사람들이 ${who}는 아닌 것 같다는 쪽으로 기울었습니다. 그 흐름을 보고 판단하세요.`
      : isMe
      ? `지목된 사람은 당신입니다. 여기서 밀리면 끝입니다. 억울함을 짧게 호소하거나 자기 묘사를 해명하세요.`
      : `지목된 사람은 ${who}입니다. 지금은 ${who} 한 사람만 다루는 시간이니 다른 사람을 새로 추궁하지 마세요.

아래 중 하나만 고르세요.
${FINAL_DEFENSE_MOVES[Math.floor(Math.random() * FINAL_DEFENSE_MOVES.length)]!.replace(/\{누구\}/g, who)}`;

  return `지금까지의 대화입니다.
${formatTranscript(ctx)}

최후 변론 중입니다.
${stance}${secretRule(ctx)}

- 위에서 당신이 이미 한 말과 겹치면 안 됩니다. 같은 판단을 두 번 말하지 마세요.

한 문장 안으로 쓰세요. 두세 글자짜리 한마디여도 됩니다.`;
}

export function guessWordPrompt(ctx: BotContext): string {
  return `지금까지의 대화입니다.
${formatTranscript(ctx)}

당신이 라이어라는 게 밝혀졌습니다. 마지막 기회로 제시어를 맞히면 라이어의 승리입니다.
지금까지 나온 묘사들을 종합해서 제시어를 추측하세요.

단어 하나만 출력하세요. 설명하거나 문장으로 쓰지 마세요.`;
}
